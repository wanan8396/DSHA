#!/usr/bin/env python3
"""Add the Linux-only verification entries this repo's metadata is missing.

`gradle/verification-metadata.xml` was generated on a Windows machine, so it pins
only the artifacts that resolve there. On Linux the resolver asks for extra
artifacts (the platform-specific aapt2 JAR, plus parent POMs the Windows
resolution never needed). Strict dependency verification then fails the build:

    > Dependency verification failed for configuration ':app:standardDebugUnitTestCompileClasspath'
      One artifact failed verification: guava-parent-33.4.8-jre.pom

Rather than weakening verification for the whole build
(`--dependency-verification=off|lenient`) or blindly accepting whatever the
resolver returns (`--write-verification-metadata`), this script adds exactly the
entries listed below, each with a checksum fetched out-of-band from the public
repository that serves it. Everything else stays strict: existing pins are
untouched, and any further unpinned artifact still fails the build loudly.
"""
import sys
from pathlib import Path

# (group, name, version, artifact file name, sha256)
# 来源：
#   aapt2-linux  -> https://dl.google.com/dl/android/maven2/com/android/tools/build/aapt2/9.1.1-14792394/
#   guava-parent -> https://repo1.maven.org/maven2/com/google/guava/guava-parent/33.4.8-jre/
ENTRIES = [
    (
        "com.android.tools.build",
        "aapt2",
        "9.1.1-14792394",
        "aapt2-9.1.1-14792394-linux.jar",
        "e7ae17af6e4093c771243e82d66462353de87befaac206bfb43e557ac1c34440",
    ),
    (
        "com.google.guava",
        "guava-parent",
        "33.4.8-jre",
        "guava-parent-33.4.8-jre.pom",
        "a03c5199a1be14443df7fd40ba8673b1c6aae04deef6688ce7d573ea489e3a20",
    ),
]

INDENT_COMPONENT = "      "
INDENT_ARTIFACT = "         "
INDENT_SHA = "            "


def artifact_block(name, sha, newline):
    return newline.join(
        [
            f'{INDENT_ARTIFACT}<artifact name="{name}">',
            f'{INDENT_SHA}<sha256 value="{sha}" origin="Generated by Gradle"/>',
            f"{INDENT_ARTIFACT}</artifact>",
        ]
    )


def insert_into_component(text, group, component, version, artifact, sha, newline):
    open_tag = (
        f'{INDENT_COMPONENT}<component group="{group}" name="{component}" version="{version}">'
    )
    start = text.index(open_tag)
    end = text.index("</component>", start)
    head = text[:end]
    body = head.rstrip()
    gap = head[len(body):]
    return body + newline + artifact_block(artifact, sha, newline) + gap + text[end:]


def append_component(text, group, component, version, artifact, sha, newline):
    # 新 component 必须落在 <components> 里：放到根节点下 Gradle 会报
    # "Invalid dependency verification metadata file: <component> must be found under the <components> tag"。
    close = text.rindex("</components>")
    head = text[:close]
    body = head.rstrip()
    gap = head[len(body):]
    block = newline.join(
        [
            f'{INDENT_COMPONENT}<component group="{group}" name="{component}" version="{version}">',
            artifact_block(artifact, sha, newline),
            f"{INDENT_COMPONENT}</component>",
        ]
    )
    return body + newline + block + gap + text[close:]


def main():
    path = Path(sys.argv[1] if len(sys.argv) > 1 else "gradle/verification-metadata.xml")
    text = path.read_text(encoding="utf-8")
    newline = "\r\n" if "\r\n" in text else "\n"
    added = 0
    for group, component, version, artifact, sha in ENTRIES:
        if f'name="{artifact}"' in text:
            print(f"OK already listed: {artifact}")
            continue
        open_tag = (
            f'{INDENT_COMPONENT}<component group="{group}" name="{component}" version="{version}">'
        )
        if open_tag in text:
            text = insert_into_component(text, group, component, version, artifact, sha, newline)
        else:
            text = append_component(text, group, component, version, artifact, sha, newline)
        print(f"OK added {artifact} sha256={sha[:16]}...")
        added += 1
    if added:
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path} (+{added})")


if __name__ == "__main__":
    main()
